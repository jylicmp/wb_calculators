"""New Metric/BCP data-requirement helpers only; no copy of upstream NeededData.

AA=<uW|i*d uW>, FF=<d uW|d uW>; see eq:external-data.
Declaring FF does not implement its construction in a System_w90 loader.
"""

def metric_required_matrices(*, external_terms=True, force_internal_terms_only=False):
    """Return required real-space matrix names for Metric and DerMetric.

    Hamiltonian derivatives and generalized derivatives are generated by data_K.
    AA alone cannot replace FF in a truncated Wannier representation.
    """
    if force_internal_terms_only or not external_terms:
        return frozenset({'Ham'})
    return frozenset({'Ham', 'AA', 'FF'})


def validate_metric_data(data_K, *, external_terms=True):
    """Fail early on missing matrices for an R-space system, without fabricating FF.

    Analytic/custom data_K providers without an R-matrix registry are checked by
    their covariant accessors. This does not modify the upstream loader registry.
    """
    system = getattr(data_K, 'system', None)
    if system is None or not hasattr(system, 'has_R_mat'):
        return
    required = metric_required_matrices(
        external_terms=external_terms,
        force_internal_terms_only=getattr(data_K, 'force_internal_terms_only', False))
    missing = sorted(name for name in required if not system.has_R_mat(name))
    if missing:
        raise ValueError('Metric/DerMetric requires missing matrices: ' + ', '.join(missing)
                         + '. Supply consistent AA/FF data for the full geometry, or explicitly '
                         'use kwargs_formula={"external_terms": False} for the internal model.')


def bcp_required_matrices(*, external_terms=True, force_internal_terms_only=False):
    """Finite-Wannier-space BCP needs Ham and, for external/cross terms, AA.

    DerBCP/Der2BCP generate Ham derivatives through order 2/3 and AA
    derivatives through order 1/2 from these R-space matrices. No FF is used.
    """
    if force_internal_terms_only or not external_terms:
        return frozenset({'Ham'})
    return frozenset({'Ham', 'AA'})


def validate_bcp_data(data_K, *, external_terms=True):
    """Check existing R-space data; does not create matrices or loader flags."""
    system = getattr(data_K, 'system', None)
    if system is None or not hasattr(system, 'has_R_mat'):
        return
    required = bcp_required_matrices(external_terms=external_terms,
        force_internal_terms_only=getattr(data_K, 'force_internal_terms_only', False))
    missing = sorted(name for name in required if not system.has_R_mat(name))
    if missing:
        raise ValueError('BCP requires missing matrices: ' + ', '.join(missing)
                         + '. Supply consistent Ham/AA, or select external_terms=False.')
